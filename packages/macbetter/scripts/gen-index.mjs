// Rebuilds src/index.ts and src/styles/components/index.css from what's on disk,
// so adding a component never means editing a shared file by hand.
import { readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const src = join(dirname(fileURLToPath(import.meta.url)), "..", "src")

const components = readdirSync(join(src, "components"))
  .filter((file) => file.endsWith(".tsx"))
  .map((file) => file.replace(/\.tsx$/, ""))
  .sort()

const styles = readdirSync(join(src, "styles", "components"))
  .filter((file) => file.endsWith(".css") && file !== "index.css")
  .sort()

writeFileSync(
  join(src, "index.ts"),
  [
    "// Generated by scripts/gen-index.mjs. Do not edit.",
    ...components.map((name) => `export * from "./components/${name}"`),
    'export * from "./lib/cx"',
    'export * from "./lib/derive"',
    'export * from "./lib/platform"',
    'export * from "./lib/theme"',
    "",
  ].join("\n")
)

writeFileSync(
  join(src, "styles", "components", "index.css"),
  [
    "/* Generated by scripts/gen-index.mjs. Do not edit. */",
    ...styles.map((file) => `@import "./${file}";`),
    "",
  ].join("\n")
)

console.log(`${components.length} components, ${styles.length} stylesheets`)

await import("./style-deps.mjs")
